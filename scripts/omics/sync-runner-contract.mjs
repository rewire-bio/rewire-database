/** Explicit maintainer import; builds never require a runner checkout. */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/omics/sync-runner-contract.mjs /path/to/rewire-benchmarks");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const resources = path.join(source, "packages/rewirebench/src/rewirebench/resources");
const raw = fs.readFileSync(path.join(resources, "sequence-submission-contract.json"));
const contract = JSON.parse(raw);
if (contract.schema_version !== "1.0" || !contract.protocols) throw new Error("Unsupported contract");
const digest = crypto.createHash("sha256").update(raw).digest("hex");
const fixtures = path.join(root, "services/omics/test/sequence-fixtures");
fs.mkdirSync(fixtures, { recursive: true });
fs.writeFileSync(path.join(fixtures, "contract.json"), raw);
fs.copyFileSync(path.join(resources, "sequence-submission-fixtures.json"), path.join(fixtures, "cases.json"));
fs.writeFileSync(path.join(root, "services/omics/src/sdk-sequence-reference.ts"),
  `// Generated by scripts/omics/sync-runner-contract.mjs; source SHA256 ${digest}.\n` +
  `// Definitions only: declarations never establish scientific reproduction.\n` +
  `export const sequenceContract = ${JSON.stringify(contract, null, 2)};\n`);
console.log(`Imported sequence submission contract ${digest}`);
